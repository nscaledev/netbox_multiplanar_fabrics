def terminal_pair(node, *, input_name='line', output_name='load', input_v=None, output_v=None, input_a=None, output_a=None, counters):
    line = upsert_terminal(
        node,
        name=input_name,
        role=TerminalRoleChoices.ROLE_LINE,
        direction=TerminalDirectionChoices.DIRECTION_SINK,
        voltage=input_v,
        amperage=input_a,
        index=1,
        counters=counters,
    )
    load = upsert_terminal(
        node,
        name=output_name,
        role=TerminalRoleChoices.ROLE_LOAD,
        direction=TerminalDirectionChoices.DIRECTION_SOURCE,
        voltage=output_v,
        amperage=output_a,
        index=2,
        counters=counters,
    )
    return line, load


