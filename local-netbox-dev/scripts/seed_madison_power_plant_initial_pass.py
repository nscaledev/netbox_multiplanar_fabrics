def upsert_node(power_system, site, *, name, kind, role='', parent=None, model='', manufacturer='', input_v=None, output_v=None, capacity_kw=None, counters):
    slug = stable_slug('node', name)
    obj, created = ElectricalNode.objects.get_or_create(
        slug=slug,
        defaults={
            'name': name,
            'power_system': power_system,
            'site': site,
        },
    )
    phase_mode = PhaseModeChoices.MODE_THREE_PHASE
    desired = {
        'name': name,
        'slug': slug,
        'power_system': power_system,
        'site': site,
        'parent_node': parent,
        'node_kind': kind,
        'equipment_role': role,
        'manufacturer': manufacturer,
        'model': model,
        'install_state': TopologyStateChoices.STATE_PLANNED,
        'topology_state': TopologyStateChoices.STATE_PLANNED,
        'rated_input_voltage_min': Decimal(str(input_v)) if input_v is not None else None,
        'rated_input_voltage_max': Decimal(str(input_v)) if input_v is not None else None,
        'rated_output_voltage_min': Decimal(str(output_v)) if output_v is not None else None,
        'rated_output_voltage_max': Decimal(str(output_v)) if output_v is not None else None,
        'frequency_hz': Decimal('60.00'),
        'phase_mode': phase_mode,
        'pole_count': 3,
        'installed_capacity_kw': q2(capacity_kw) if capacity_kw is not None else None,
        'usable_capacity_kw': q2(capacity_kw) if capacity_kw is not None else None,
        'description': short_description(f'{SOURCE_MARKER}; source: ENOVUM MAD-1 electrical drawings.'),
    }
    counters['electrical_node_created' if created else 'electrical_node_seen'] += 1
    return save_changed(obj, desired, counters, 'electrical_node')


