def stable_slug(*parts, max_length=100):
    raw = '-'.join(str(part) for part in parts if part is not None)
    base = slugify(raw) or 'object'
    digest = hashlib.sha1(raw.encode()).hexdigest()[:8]
    suffix = f'-{digest}'
    return f'{base[: max_length - len(suffix)]}{suffix}'


def short_description(text):
    return text[:200]


def unique_display_name(*parts, max_length=100):
    raw = ' '.join(str(part) for part in parts if part is not None)
    if len(raw) <= max_length:
        return raw
    digest = hashlib.sha1(raw.encode()).hexdigest()[:8]
    return f'{raw[: max_length - 9]}-{digest}'


def q2(value):
    return Decimal(str(value)).quantize(Decimal('0.01'))


def save_changed(obj, desired, counters, key):
    changed = False
    for field, value in desired.items():
        if getattr(obj, field) != value:
            setattr(obj, field, value)
            changed = True
    if changed:
        obj.full_clean()
        obj.save()
    counters[f'{key}_updated' if changed else f'{key}_unchanged'] += 1
    return obj


def upsert_power_system(site, counters):
    slug = stable_slug('power-system', POWER_SYSTEM_NAME)
